package tray

import (
	"fyne.io/fyne/v2"
	"fyne.io/systray"
)

// Manager управляет системным треем
type Manager struct {
	window fyne.Window
}

// New создает новый менеджер системного трея
func New(window fyne.Window) *Manager {
	return &Manager{
		window: window,
	}
}

// Start запускает системный трей (должен вызываться из отдельной горутины)
func (m *Manager) Start() {
	systray.Run(m.onReady, m.onExit)
}

func (m *Manager) onReady() {
	systray.SetTemplateIcon(iconData, iconData)
	systray.SetTitle("ProjectT")
	systray.SetTooltip("ProjectT")

	open := systray.AddMenuItem("Open", "Open application")
	close := systray.AddMenuItem("Close", "Close to tray")
	systray.AddSeparator()
	quit := systray.AddMenuItem("Quit", "Quit application")

	go func() {
		for {
			select {
			case <-open.ClickedCh:
				fyne.Do(func() {
					m.window.Show()
					m.window.RequestFocus()
				})
			case <-close.ClickedCh:
				fyne.Do(func() {
					m.window.Hide()
				})
			case <-quit.ClickedCh:
				fyne.Do(func() {
					fyne.CurrentApp().Quit()
				})
			}
		}
	}()
}

func (m *Manager) onExit() {
}

